function [hexdfitfile] = MechRecon()
% program MechRecon
%
%  Compiled by Paul Dawson from codes and scripts from MAE courses, OdfPF, 
%   pre- and post-processing tools for FEpX, other research projects
%   in the Deformation Processes Lab at Cornell University.
%
% Evaluate discrete harmonic expansion weights for HEXD data
%  Data takes the form of an average stess tensor for each grain
%  Employs an optimization procedure to find expansion weights while
%  imposing constraints for equilibrium internal to grains and traction
%  balances across grain boundaries.
%


%    Input data are read following prompts 
%
%    Input:   (1) nummodes  -- integer number of modes
%             (2) mechmonicsvtkname -- base names of output files generated by MechMonics
%             (3) nepermeshname -- string with the name of the MechMonics GBG finite element mesh
%             (4) graindataname -- file of element-based grain stresses from HEXD data
%             (5) freesurfacename -- name of file with free surface vectors
%             (6) outputfilename -- string with the name of the target output file
%                                       for data fields (modal fits and
%                                       input data)

%
%     Output: 
%      (1) beta values for each mode for each component of stress for all grains
%      (2) a vtk file with the stress distribution over the polycrystal
%   
%             
%
%  stress (and beta) component ordering is:
%
%   1 -- sigxx
%   2 -- sigyy
%   3 -- sigzz
%   4 -- sigyz
%   5 -- sigxz
%   6 -- sigxy

% initial_guess_flag = 1 use values in input argument beta_guess
%                    = 0 set v0 stress average from data for mode 1; other mode values = 0

initial_guess_flag = 0;

equilibrium_weight = 0.3e0;
traction_weight    = 10.0e0;
%


%
% set up elemental shape function arrays and size parameters
%
shafac_structure = ShapeFunctionArrays();

sfac = shafac_structure.sfac;
dndxi = shafac_structure.dndxi;
dndet = shafac_structure.dndet;
dndze = shafac_structure.dndze;
nqptv = shafac_structure.nqpt;
wtqp = shafac_structure.wtqp;
nnpe = shafac_structure.nnpe;
nspe = 6;

ncomp = 6;


mechmonicsvtkname = input('Base name of microstructure and harmonic mode files created by MechMonics (with extension .mat): ', 's');

microstructurefilename =  [mechmonicsvtkname '_micro.mat' ];   
load(microstructurefilename);   


harmonicmodefilename =  [mechmonicsvtkname '_modes.mat' ];   
load(harmonicmodefilename);   

grad_US = harmonicmodefile.grad_US;
grains = microstructurefile.grains;
phases = microstructurefile.phases;
grain_weights = microstructurefile.grain_weights;
ngrains=max(grains);


nepermeshname = input('Base name of grain-by-grain mesh files created by MechMonics (with extension .mat): ', 's');

       
grainmeshfilename =  [nepermeshname '_' 'meshfile_gbg' ];   
load(grainmeshfilename);  


numberofmodes = input('Enter the number of modes to be used in the fitting (<= number computed in MechMonics): ', 's');
nummodes = str2num(numberofmodes);

 

status = ' Completed reading the grain-by-grain mesh '

[m n]   = size(meshfilegbg.crd);
newnumnp = n;

[m n]   = size(meshfilegbg.con);
newnumel = n;

[m n]   = size(meshfilegbg.nepercrd);
nepernumnp = n;

[m n]   = size(meshfilegbg.nepercon);
nepernumel = n;
 
[m n]   = size(meshfilegbg.nepergrn4np);
numgrn4np = n;

freesurfacename = input('File name with free surface vectors (with extension .mat): ', 's');     
freesurfacefilename =  [freesurfacename '.mat' ];   
arrayname = load(freesurfacefilename); 
samplefreesurfacevectors = arrayname.freesurfacevectors;

graindataname = input('File name with grain stresses (with extension .mat): ', 's');     
graindatafilename =  [graindataname '.mat' ];   
arrayname = load(graindatafilename);
%HEXD_Data = arrayname.solutionfilegbg.sigma_ave; 
HEXD_Data = arrayname.grainstresses; 

equilibriummatrixsize = 3*newnumel;
equilibriummatrix = zeros(6*nummodes*ngrains);
beq = zeros(6*nummodes*ngrains,1);
Aeq = zeros(6*nummodes*ngrains);

%  The objective function has contributions from the grain boundary
%  tractions and from the local equilibrium equations.  
%    The local equilibrium contribution is treated first. 
%    The traction equilibrium contibution is treated second. 
%  The equality constraint has the average grain stress from the HEXD data
%  and is dealt with along with the local equilibrium contribution


%Loop over all grains to set up the local equilibrium optimization matrices
%and the equality constraint for the HEXD average stress data


status = ' Starting local equilibrium objective function matrix '

for igrn = 1:1:ngrains
    
igrnstr = string(igrn);  

message = [' Working on Grain Number: ' igrnstr ];
disp(message)

    
grainmeshfilename =  [nepermeshname '_' 'meshfile_grn_' num2str(igrn) ];   
load(grainmeshfilename);

% Set mesh size variables from mesh coordinate and connectivity arrays
[m n]   = size(meshfile1X.crd);
numnp = n;

[m n]   = size(meshfile1X.con);
numel = n;

[m n]  = size(meshfile1X.surfnp);
numsurfel = n;

np = meshfile1X.con';
coords = meshfile1X.crd;

%
%define local variables for coordinates
%
x = coords(1,:)';
y = coords(2,:)';
z = coords(3,:)';
grain_weight = grain_weights(igrn);

%element_volumes = zeros(1,numel);

% Evaluate values of the first mode for each stress component for data 
%           save as beq for the equality constraint RHS matrix

% norm_data = norm(HEXD_Data,'fro');
% HEXD_Data = HEXD_Data/norm_data;
localbeq = zeros(nummodes*6,1);
v0 =zeros(nummodes*ncomp,1);
scalefactor = meshfile1X.US(1,1);
for icomp = 1:1:6
localbeq((icomp-1)*nummodes+1) = HEXD_Data(icomp,igrn)/scalefactor;
end

%assemble the equality constraint matrices Aeq and beq

for icomp = 1:1:6
  irow = 6*nummodes*(igrn-1)+(icomp-1)*nummodes+1;
  Aeq(irow,irow) = 1;
  beq(irow) = localbeq((icomp-1)*nummodes+1);
end

% form the intra-grain equilibrium objective function
% done at the centroid of the element

    mhat11 = zeros(1,nummodes);
    mhat22 = zeros(1,nummodes);
    mhat33 = zeros(1,nummodes);
    mhat15 = zeros(1,nummodes);
    mhat16 = zeros(1,nummodes);
    mhat24 = zeros(1,nummodes);   
    mhat26 = zeros(1,nummodes);   
    mhat34 = zeros(1,nummodes);   
    mhat35 = zeros(1,nummodes);
    mhatij = zeros(1,nummodes);
    

for   iele =1:1:numel

%  evaluate  quad point quantities for mode gradients
% . need values for the dU/dx etc at qp's (nodal point values computed and
%  saved in mechmonics; read in here as grad_US)
% . need local values of U for the element.
%   loop over nps using dndx*U using dndx at qp

  localobjectmatrix = zeros(6*nummodes);
   
  [dndx,dndy,dndz,detj,elvolume] = SFDerivatives(iele,nnpe,nqptv,wtqp,np,x,y,z,dndxi,dndet,dndze);
  
  %element_volumes(iele) = elvolume;

 for jqpt = 1:1:nqptv
 
   us_local = zeros(nummodes,1);
   grad_US_local = zeros(3,nummodes);
   mhat = zeros(3,6*nummodes);
   
   for inpe =1:1:nnpe
       inp1=np(iele,inpe); 
       inpv3=3*inp1;
       inpv2=inpv3-1;
       inpv1=inpv3-2;

       for jmode = 1:1:nummodes
       us_local(jmode) = us_local(jmode) + sfac(inpe,jqpt)*meshfile1X.US(inp1,jmode);
       grad_US_local(1,jmode) = grad_US_local(1,jmode) + sfac(inpe,jqpt)*grad_US(inpv1,jmode);
       grad_US_local(2,jmode) = grad_US_local(2,jmode) + sfac(inpe,jqpt)*grad_US(inpv2,jmode);
       grad_US_local(3,jmode) = grad_US_local(3,jmode) + sfac(inpe,jqpt)*grad_US(inpv3,jmode);
       end
   end   
  
% form the elemental object matrix
    
  for imode = 1:1:nummodes
    mhat11(1,imode) = grad_US_local(1,imode); 
    mhat22(1,imode) = grad_US_local(2,imode); 
    mhat33(1,imode) = grad_US_local(3,imode); 
    mhat15(1,imode) = grad_US_local(3,imode); 
    mhat16(1,imode) = grad_US_local(2,imode); 
    mhat24(1,imode) = grad_US_local(3,imode); 
    mhat26(1,imode) = grad_US_local(1,imode);  
    mhat34(1,imode) = grad_US_local(2,imode); 
    mhat35(1,imode) = grad_US_local(1,imode);   
  end
  
  mhat = [mhat11(:)' mhatij(:)' mhatij(:)' mhatij(:)' mhat15(:)' mhat16(:)';...
          mhatij(:)' mhat22(:)' mhatij(:)' mhat24(:)' mhatij(:)' mhat26(:)'; ...
          mhatij(:)' mhatij(:)' mhat33(:)' mhat34(:)' mhat35(:)' mhatij(:)' ];
      
%  localobjectmatrix = localobjectmatrix + wtqp(jqpt)*mhat'*mhat;   
  localobjectmatrix = localobjectmatrix + wtqp(jqpt)*elvolume*mhat'*mhat;   
  
  
 end
 
 locallobjectmatrix = localobjectmatrix*grain_weight;
% 
% % assemble elemental matrix into global matrix
 rowvalue = igrn;
 columnvalue = igrn;
% 
 rowstart = 6*nummodes*(rowvalue-1);
 columnstart = 6*nummodes*(columnvalue-1);
 lom_size2 = 6*nummodes;
  for ilocal = 1:1:lom_size2
        irow = rowstart+ilocal;
    for jlocal = 1:1:lom_size2
        jcol = columnstart+jlocal;
        equilibriummatrix(irow,jcol) = equilibriummatrix(irow,jcol)+localobjectmatrix(ilocal,jlocal);
    end
  end
  
 end

clear meshfile1X;

end

Aeq_sparse = sparse(Aeq);
clear Aeq;
equilibriummatrix_sparse = sparse(equilibriummatrix);
norm_equilibrium = norm(equilibriummatrix,'fro')
clear equilibriummatrix;

status = ' Starting surface traction vector objective function matrix '

% Now set up the traction equilibrium matrices.  To do this we first find
% all the grain boundary surface elements and determine the matching
% surface element pairs for adjoining grains.

% Determine the surface element pair array containing the surface element numbers
% of adjoining surface elements in neighboring grains.  The surface element
% pairs will be used for constructing the traction constraints.

igrnstr = string(igrn);  

status = ' Setting up adjoining element surface arrays '

[surfconstraint,grainconstraint,constraintspergrain,constraintpairs,contarget] = AdjoiningGrainSurfaceElements(microstructurefile,nepermeshname,grainmeshfilename,meshfilegbg,samplefreesurfacevectors);

[numtracconstraints,dum] = size(constraintpairs);
tractmatrixsize = max(contarget);
tractionmatrix = zeros(6*nummodes*ngrains);

normals_data  = zeros(6,numtracconstraints);
centroids_data= zeros(6,numtracconstraints);
patch_error = zeros(1,numtracconstraints);

normvectone = zeros(3,numtracconstraints);
normvecttwo = zeros(3,numtracconstraints);
% 

check_pairs = zeros(numtracconstraints,1);
check_freesurf = zeros(numtracconstraints,1);
check_assembly1 = zeros(numtracconstraints,1);
check_assembly4 = zeros(numtracconstraints,1);

% set up the constraint matrix for the grain interface tractions


status = ' Starting loop over all element surfaces with traction constraint in objective function '

for icon = 1:1:numtracconstraints
    
    
iconstr = string(icon);  

status = [' Working on surface tractions for element pair  ' iconstr ];
    
elementmtilde = zeros(6,2*6*nummodes);
elementobjectmatrix = zeros(2*6*nummodes);

%get nodal point values for each mode at np1
surfele1 = surfconstraint(1,icon);
surfele2 = surfconstraint(2,icon);

grain1 = grainconstraint(1,icon);
grain2 = grainconstraint(2,icon);

if(grain2==-1)
    grain_weight = grain_weights(grain1);
else
    grain_weight = (grain_weights(grain1)+grain_weights(grain2))/2.0;
end


if(constraintpairs(icon)==icon)
    
    check_pairs(icon) = 1;

for jside = 1:1:2
    
    
localmtilde = zeros(6,6*nummodes);
localobjmatrix = zeros(6*nummodes);
    
if((jside==2) & (grain2==(-1))) 
    
 check_freesurf(icon) = 1;
 
else
 
igrn = grainconstraint(jside,icon);   
    
grainmeshfilename =  [nepermeshname '_' 'meshfile_grn_' num2str(igrn) ];   
load(grainmeshfilename);

% Set mesh size variables from mesh coordinate and connectivity arrays
[m n]   = size(meshfile1X.crd);
numnp = n;

[m n]   = size(meshfile1X.con);
numel = n;

[m n]  = size(meshfile1X.surfnp);
numsurfel = n;


surfelej = surfconstraint(jside,icon);
np1 = meshfile1X.surfnp(1,surfelej);
np3 = meshfile1X.surfnp(3,surfelej);
np5 = meshfile1X.surfnp(5,surfelej);


%get area value and normal vectors for the surface
surfarea = meshfile1X.surfarea(surfelej);
surfnorm(:) = meshfile1X.surfnormal(:,surfelej);
normalmatrix = [ surfnorm(1) 0 0 0 surfnorm(3) surfnorm(2); 0 surfnorm(2) 0 surfnorm(3) 0 surfnorm(1); 0 0 surfnorm(3) surfnorm(2) surfnorm(1) 0 ];

if(jside==1) 
    normvectone(:,icon) = surfnorm(:);
    normals_data([1 2 3],icon) = surfnorm([1 2 3]);
else
    normvecttwo(:,icon) = surfnorm(:);
    normals_data([4 5 6],icon) = surfnorm([1 2 3]);
end
surfUS = zeros(nummodes,1);

%get mode values for surface nodes and average
for isurfus = 1:1:nummodes
surfUS(isurfus) = (meshfile1X.US(np1,isurfus)+meshfile1X.US(np3,isurfus)+meshfile1X.US(np5,isurfus))/3.;
end

%set up Mtilde matrix
for istrcomp = 1:1:6
for imode = 1:1:nummodes
itarget = (istrcomp-1)*nummodes+imode;
localmtilde(istrcomp,itarget) = surfarea*surfUS(imode);
end
end

if(jside==2)
    localmtilde = -localmtilde;
end

% put into surface element constraint matrix
 columnvalue = jside; 
 columnstart = 6*nummodes*(columnvalue-1);
for istrcomp = 1:1:6
    columnposition = columnstart+(istrcomp-1)*nummodes;
for imode = 1:1:nummodes
itarget = columnposition+imode;
ilocal  = nummodes*(istrcomp-1)+imode;
elementmtilde(istrcomp,itarget) = localmtilde(istrcomp,ilocal);
end
end

end

end


% form elemental traction objective function matrix

elementobjectmatrix = elementmtilde'*normalmatrix'*normalmatrix*elementmtilde;

% assemble into global traction objective function matrix

ifreesurfflag = grainconstraint(2,icon); 

lom_size2 = 6*nummodes;  

if(ifreesurfflag~=(-1))

check_assembly4(icon) = 1;
for iside = 1:1:2
for jside = 1:1:2
    
con_num_iside = grainconstraint(iside,icon);
con_num_jside = grainconstraint(jside,icon);

rowblock = contarget(con_num_iside);
columnblock = contarget(con_num_jside);

globalrowstart    = 6*nummodes*(rowblock-1);
globalcolumnstart = 6*nummodes*(columnblock-1);

localrowstart =(iside-1)*6*nummodes;
localcolstart =(jside-1)*6*nummodes;

             for ilocal = 1:1:lom_size2
                irow1 = globalrowstart+ilocal;
                irow2 = localrowstart+ilocal;
             for jlocal = 1:1:lom_size2
                jcol1 = globalcolumnstart+jlocal;
                jcol2 = localcolstart+jlocal;
                tractionmatrix(irow1,jcol1) = tractionmatrix(irow1,jcol1)+ grain_weight*elementobjectmatrix(irow2,jcol2); 
             end
             end
  
end
end

else
    
check_assembly1(icon) = -1;
    
con_num_iside = grainconstraint(1,icon);
con_num_jside = grainconstraint(1,icon);

rowblock = contarget(con_num_iside);
columnblock = contarget(con_num_jside);

globalrowstart    = 6*nummodes*(rowblock-1);
globalcolumnstart = 6*nummodes*(columnblock-1);

localrowstart =(iside-1)*6*nummodes;
localcolstart =(jside-1)*6*nummodes;
    
                for ilocal = 1:1:lom_size2
                irow1 = globalrowstart+ilocal;
                irow2 = localrowstart+ilocal;
             for jlocal = 1:1:lom_size2
                jcol1 = globalcolumnstart+jlocal;
                jcol2 = localcolstart+jlocal;
                tractionmatrix(irow1,jcol1) = tractionmatrix(irow1,jcol1)+grain_weight*elementobjectmatrix(irow2,jcol2); 
             end
             end
  
    
end

end
end

tractionmatrix_sparse = sparse(tractionmatrix);
norm_traction = norm(tractionmatrix,'fro')
clear tractionmatrix;


status = ' Rescaling equilibrium and traction objective function matrices '

% norm_traction = norm(tractionmatrix,'fro')
% norm_equilibrium = norm(equilibriummatrix,'fro')
% 
% C = traction_weight*tractionmatrix/norm_traction + equilibrium_weight*equilibriummatrix/norm_equilibrium;

C = traction_weight*tractionmatrix_sparse/norm_traction + equilibrium_weight*equilibriummatrix_sparse/norm_equilibrium;

C_sparse = sparse(C);

if(initial_guess_flag == 0) 
    v0 = beq;
else 

    betavectorfilename = input('File name for vector with initial guess of weights (with extension .mat): ', 's');
    beta_data = load([betavectorfilename '.mat']);
    v0=beta_data.beta_vector;
end

v  = zeros(nummodes*ngrains*6,1);

clear C tractionmatrix_sparse equilibriummatrix_sparse;

%
% Set up the call to fmincon to determine the beta values


status = ' Turn matrices over to fmincon to perform optimization '

%
%options = optimoptions(@fmincon,'MaxIterations',50,'MaxFunctionEvaluations',1000000,'Display','iter','Algorithm','interior-point','OptimalityTolerance',1e-12,'StepTolerance',1e-10)
options = optimoptions(@fmincon,'MaxIterations',20,'MaxFunctionEvaluations',1000000,'Display','iter','Algorithm','interior-point','OptimalityTolerance',1e-12,'StepTolerance',1e-10)

[v,fval,exitflag,output] = fmincon(@(v)v'*C_sparse*v,v0,[],[],Aeq_sparse,beq,[],[],[],options);

% v=v*norm_data;

beta_all = v;

clear C_sparse Aeq_sparse v v0 ;

sigmanp = zeros(6,newnumnp);
% 


status = 'Saving results '
 
for igrn = 1:1:ngrains
    
grainmeshfilename =  [nepermeshname '_' 'meshfile_grn_' num2str(igrn) ];   
load(grainmeshfilename);

% Set mesh size variables from mesh coordinate and connectivity arrays
[m n]   = size(meshfile1X.crd);
numnp = n;

[m n]   = size(meshfile1X.con);
numel = n;

igrntarget = (igrn-1)*6*nummodes;

beta_1=zeros(1,nummodes);
beta_2=zeros(1,nummodes);
beta_3=zeros(1,nummodes);
beta_4=zeros(1,nummodes);
beta_5=zeros(1,nummodes);
beta_6=zeros(1,nummodes);

for imodes = 1:1:nummodes
    beta_1(imodes) = beta_all(igrntarget+imodes);   
    beta_2(imodes) = beta_all(igrntarget+nummodes+imodes);  
    beta_3(imodes) = beta_all(igrntarget+nummodes*2+imodes);  
    beta_4(imodes) = beta_all(igrntarget+nummodes*3+imodes);  
    beta_5(imodes) = beta_all(igrntarget+nummodes*4+imodes);  
    beta_6(imodes) = beta_all(igrntarget+nummodes*5+imodes);  
    
end

sigmagrn = zeros(6,numnp);

for imode = 1:1:nummodes   
    sigmagrn(1,:) = sigmagrn(1,:) + beta_1(imode)*meshfile1X.US(:,imode)';
    sigmagrn(2,:) = sigmagrn(2,:) + beta_2(imode)*meshfile1X.US(:,imode)';
    sigmagrn(3,:) = sigmagrn(3,:) + beta_3(imode)*meshfile1X.US(:,imode)';
    sigmagrn(4,:) = sigmagrn(4,:) + beta_4(imode)*meshfile1X.US(:,imode)';
    sigmagrn(5,:) = sigmagrn(5,:) + beta_5(imode)*meshfile1X.US(:,imode)';
    sigmagrn(6,:) = sigmagrn(6,:) + beta_6(imode)*meshfile1X.US(:,imode)';
end

 
for inp = 1:1:numnp
    itarget = meshfile1X.npcrossref(inp);
    sigmanp(:,itarget)= sigmagrn(:,inp);
end
   
   clear meshfile1X;  
end


    status = ' Finished all grains; begin writing plotting files ' 

 hexd_stress = zeros(6,newnumel);

 for inumel =1:1:newnumel
    grnnum = grains(inumel);
    hexd_stress(:,inumel) = HEXD_Data(:,grnnum);
 end


% Add results for all modes for all grains

hexdfitfile    = Data_Structure_Stress_Recovery(hexd_stress, sigmanp, beta_all);


save('hexd_stress.mat',"hexd_stress");
save('sigmanp.mat',"sigmanp");
save('beta_all.mat',"beta_all");


outputfilename = input('Base name of output file names: ', 's');

save([outputfilename 'HEXD.mat'],'hexdfitfile');

SUF = 'vtk';

file_hexdfit_VTK = fopen(sprintf('%s.%s', [outputfilename], SUF), 'w');
% 
 Export_Stress_Recovery_VTK(file_hexdfit_VTK, hexdfitfile , meshfilegbg,  phases,grains);
% 
 status = 'Completed writing results to VTK file'

clear all;
